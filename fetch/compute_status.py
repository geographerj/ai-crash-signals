"""Compute the signal level and write data/status.json.

Thresholds come from fetch/rules.json. assets/status.js implements the same logic
in the browser; keep the two in step (the page warns if they disagree).
"""
import json
import re
import subprocess
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
RULES = json.loads((ROOT / "fetch" / "rules.json").read_text(encoding="utf-8"))
OPS = {
    "==": lambda a, b: a == b,
    ">=": lambda a, b: a >= b,
    "<=": lambda a, b: a <= b,
    ">": lambda a, b: a > b,
    "<": lambda a, b: a < b,
}
FRED_URL = "https://fred.stlouisfed.org/series/"


def write_js(key, obj):
    """Write data/<key>.js so the page also works from file:// (no fetch needed)."""
    body = json.dumps(obj, separators=(",", ":"))
    text = ("/* generated by fetch/compute_status.py; do not edit */\n"
            "window.__DATA = window.__DATA || {};\n"
            "window.__DATA." + key + " = " + body + ";\n")
    (DATA / (key + ".js")).write_text(text, encoding="utf-8")


def build_version(now):
    """Short git hash if available, else a UTC timestamp. Used to bust browser caches."""
    try:
        out = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True,
                             text=True, timeout=10)
        v = out.stdout.strip()
        if out.returncode == 0 and re.fullmatch(r"[0-9a-f]+", v):
            return v
    except Exception:  # noqa: BLE001
        pass
    return now.strftime("%Y%m%d%H%M")


def stamp_index(version):
    """Rewrite every ?v=<hex> token in index.html (idempotent)."""
    p = ROOT / "index.html"
    html = p.read_text(encoding="utf-8")
    new = re.sub(r"\?v=[0-9a-f]+", "?v=" + version, html)
    if new != html:
        p.write_text(new, encoding="utf-8")


def cond_true(c, numeric):
    v = numeric.get(c["field"])
    if v is None:
        return False
    return OPS[c["op"]](v, c["value"])


def any_group(groups, numeric):
    return any(all(cond_true(c, numeric) for c in g) for g in groups)


def manual_status(rule, numeric):
    if any_group(rule["tripped"], numeric):
        return "tripped"
    if any_group(rule["watch"], numeric):
        return "watch"
    return "clear"


def days_between(a, b):
    return (datetime.strptime(b, "%Y-%m-%d") - datetime.strptime(a, "%Y-%m-%d")).days


def macro_indicators(fred):
    m = RULES["macro"]
    d = fred["derived"]
    out = []

    def add(id_, status, value_text, as_of, url):
        out.append({"id": id_, "group": "macro", "name": m[id_]["name"], "status": status,
                    "value_text": value_text, "trigger_text": m[id_]["trigger_text"],
                    "as_of": as_of, "source_url": url})

    sp = d["sp500"]
    r = m["sp500_trend"]
    if sp["last_month_end_below"]:
        st = "tripped"
    elif sp["provisional_below"]:
        st = "watch"
    else:
        st = "clear"
    prov = " (provisional until month-end)" if sp["provisional"] else ""
    add("sp500_trend", st,
        f"Close {sp['latest_close']:,.0f} vs provisional 10-month average {sp['provisional_sma']:,.0f}{prov}; "
        f"last month-end avg {sp['last_month_end_sma']:,.0f}",
        sp["latest_date"], FRED_URL + "SP500")

    y = d["yield_curve"]
    r = m["yield_curve"]
    if y["neg_run"] >= r["tripped_consecutive_days"]:
        st = "tripped"
    elif 0 <= y["latest"] <= r["watch_max"]:
        st = "watch"
    else:
        st = "clear"
    add("yield_curve", st, f"10y-3m {y['latest']:+.2f} pts; 10y-2y {y['t10y2y']:+.2f}", y["date"], FRED_URL + "T10Y3M")

    b = d["baa"]
    r = m["baa_spread"]
    if b["latest"] >= r["tripped_level"] or b["rise_bp"] >= r["tripped_rise_bp"]:
        st = "tripped"
    elif b["rise_bp"] >= r["watch_rise_bp"]:
        st = "watch"
    else:
        st = "clear"
    add("baa_spread", st, f"{b['latest']:.2f} pts; {b['rise_bp']:+.0f} bp from 12-month low ({b['low_12m']:.2f})", b["date"], FRED_URL + "BAA10Y")

    h = d["hy"]
    r = m["hy_oas"]
    if h["latest"] >= r["tripped_level"] or h["change_3m_bp"] >= r["tripped_rise_bp"]:
        st = "tripped"
    elif h["change_3m_bp"] >= r["watch_rise_bp"]:
        st = "watch"
    else:
        st = "clear"
    add("hy_oas", st, f"{h['latest']:.2f} pts; {h['change_3m_bp']:+.0f} bp over 3 months", h["date"], FRED_URL + "BAMLH0A0HYM2")

    c = d["claims"]
    r = m["claims"]
    if c["pct_above_low"] >= r["tripped_pct"]:
        st = "tripped"
    elif c["pct_above_low"] >= r["watch_pct"]:
        st = "watch"
    else:
        st = "clear"
    add("claims", st, f"4-week avg {c['latest_avg4']:,.0f}; {c['pct_above_low']:+.1f}% vs 52-week low ({c['low_52w']:,.0f})", c["date"], FRED_URL + "ICSA")

    s = d["sahm"]
    r = m["sahm"]
    if s["latest"] >= r["tripped_value"]:
        st = "tripped"
    elif s["latest"] >= r["watch_value"]:
        st = "watch"
    else:
        st = "clear"
    add("sahm", st, f"{s['latest']:.2f} (unemployment {d['unrate']['latest']:.1f}%)", s["date"], FRED_URL + "SAHMREALTIME")

    f = d["fed"]
    mv = f["last_move_60d"]
    move_txt = f"last move a {mv['direction']} on {mv['date']}" if mv else "no move in the last 60 days"
    est = " (estimated)" if f.get("estimated") else ""
    add("fed_path", "context",
        f"Target range {f['target_low']:.2f}-{f['target_high']:.2f}%{est}; effective {f['effective']:.2f}%; {move_txt}",
        f["date"], FRED_URL + "DFF")
    return out


def manual_indicators(manual, today):
    out = []
    rules = {**RULES["ai"], **RULES["other_manual"]}
    for ind in manual["indicators"]:
        rule = rules[ind["id"]]
        st = manual_status(rule, ind["numeric"])
        out.append({"id": ind["id"], "group": ind["group"], "name": ind["name"], "status": st,
                    "value_text": ind["value"], "trigger_text": rule["trigger_text"],
                    "as_of": ind["as_of"], "source_url": ind["source_url"],
                    "stale": days_between(ind["as_of"], today) > RULES["stale_days"]})
    return out


def phrase(ind):
    rule = {**RULES["macro"], **RULES["ai"], **RULES["other_manual"]}[ind["id"]]
    return rule["tripped_phrase"] if ind["status"] == "tripped" else rule["watch_phrase"]


def overall(inds, fred, manual):
    by = {i["id"]: i for i in inds}
    ai_ids = RULES["ai_ids"]
    ai_tripped = sum(1 for i in ai_ids if by[i]["status"] == "tripped")
    ai_any = any(by[i]["status"] in ("tripped", "watch") for i in ai_ids)
    sp_t = by["sp500_trend"]["status"] == "tripped"
    baa_t = by["baa_spread"]["status"] == "tripped"
    hy_t = by["hy_oas"]["status"] == "tripped"
    confirming = sp_t or baa_t or hy_t
    level2 = ai_tripped >= 2 and confirming
    me = fred["derived"]["sp500"]["month_ends"]
    two_months = len(me) >= 2 and me[-1][1] < me[-1][2] and me[-2][1] < me[-2][2]
    num = {i["id"]: i["numeric"] for i in manual["indicators"]}
    junk = bool(num["ai_credit"].get("oracle_junk"))
    hy_level = fred["derived"]["hy"]["latest"] >= RULES["macro"]["hy_oas"]["tripped_level"]
    level3 = level2 and two_months and (junk or by["ai_lab_funding"]["status"] == "tripped" or hy_level)
    watch_any = (ai_any or by["yield_curve"]["status"] == "tripped"
                 or by["baa_spread"]["status"] in ("tripped", "watch"))
    if level3:
        return 3
    if level2:
        return 2
    if watch_any:
        return 1
    return 0


def reason(level, inds):
    name = RULES["levels"][str(level)]["name"]
    ai = [phrase(i) for i in inds if i["id"] in RULES["ai_ids"] and i["status"] in ("tripped", "watch")]
    mac = [phrase(i) for i in inds if i["group"] == "macro" and i["id"] != "fed_path" and i["status"] in ("tripped", "watch")]
    if level == 0 and not ai and not mac:
        return "Normal: no AI or macro indicator is tripped or on watch."
    parts = []
    if ai:
        parts.append(" and ".join(ai) if len(ai) <= 2 else ", ".join(ai[:-1]) + " and " + ai[-1])
    if mac:
        parts.append("macro flags: " + ", ".join(mac))
        tail = "."
    else:
        tail = "; all macro indicators clear."
    body = "; ".join(parts) if parts else "no AI indicators flagged"
    return f"{name}: {body}{tail}"


def main():
    fred = json.loads((DATA / "fred.json").read_text(encoding="utf-8"))
    manual = json.loads((DATA / "manual.json").read_text(encoding="utf-8"))
    now = datetime.now(timezone.utc)
    today = now.strftime("%Y-%m-%d")
    inds = macro_indicators(fred) + manual_indicators(manual, today)
    for i in inds:
        i.setdefault("stale", False)
    level = overall(inds, fred, manual)
    text = reason(level, inds)
    me = fred["derived"]["sp500"]["month_ends"]
    history = [{"month": d[:7], "close": c, "sma10": round(s, 2), "tripped": c < s} for d, c, s in me[-12:]]
    status = {"computed_at": now.isoformat(timespec="seconds"), "level": level,
              "level_name": RULES["levels"][str(level)]["name"], "reason": text,
              "build": build_version(now), "indicators": inds, "sp500_trend_history": history}
    (DATA / "status.json").write_text(json.dumps(status, indent=1), encoding="utf-8")

    log_path = DATA / "log.json"
    log = json.loads(log_path.read_text(encoding="utf-8")) if log_path.exists() else []
    if not log or log[0]["level"] != level:
        active = [f"{i['id']} ({i['status']})" for i in inds
                  if i["status"] in ("tripped", "watch") and i["id"] != "fed_path"]
        log.insert(0, {"date": today, "level": level, "level_name": status["level_name"],
                       "active": active, "note": text})
        log_path.write_text(json.dumps(log, indent=1), encoding="utf-8")
        print("log entry added")
    log = json.loads(log_path.read_text(encoding="utf-8"))
    write_js("status", status)
    write_js("manual", manual)
    write_js("log", log)
    write_js("fred", fred)
    write_js("rules", RULES)
    stamp_index(status["build"])
    print(f"level {level} {status['level_name']}: {text}")
    for i in inds:
        print(f"  {i['id']:20s} {i['status']:8s} {i['as_of']}{' STALE' if i['stale'] else ''}")


if __name__ == "__main__":
    main()
